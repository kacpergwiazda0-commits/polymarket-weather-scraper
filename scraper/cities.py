CITIES_BY_NAME: Dict[str, CityConfig] = {c.name.lower(): c for c in POLYMARKET_CITIES}


def get_city(identifier: str) -> Optional[CityConfig]:
    key = identifier.strip().lower().replace("-", "_").replace(" ", "_")
    if key in CITIES_BY_SLUG:
        return CITIES_BY_SLUG[key]
    return CITIES_BY_NAME.get(identifier.strip().lower())
