def encode_geohash(latitude: float, longitude: float, precision: int = 9) -> str:
    """Encode latitude and longitude into a standard base32 geohash (used by UK Met Office URLs)."""
    base32 = "0123456789bcdefghjkmnpqrstuvwxyz"
    lat_interval = [-90.0, 90.0]
    lon_interval = [-180.0, 180.0]
    geohash: List[str] = []
    bits = [16, 8, 4, 2, 1]
    bit = 0
    ch = 0
    even = True
    while len(geohash) < precision:
        if even:
            mid = (lon_interval[0] + lon_interval[1]) / 2
            if longitude > mid:
                ch |= bits[bit]
                lon_interval[0] = mid
            else:
                lon_interval[1] = mid
        else:
            mid = (lat_interval[0] + lat_interval[1]) / 2
            if latitude > mid:
                ch |= bits[bit]
                lat_interval[0] = mid
            else:
                lat_interval[1] = mid
        even = not even
        if bit < 4:
            bit += 1
        else:
            geohash.append(base32[ch])
            bit = 0
            ch = 0
    return "".join(geohash)


@dataclass(frozen=True)
class CityConfig:
    """Configuration for a Polymarket 'Highest temperature in (city) on (day)?' city."""

    name: str
    slug: str
    polymarket_title_city: str
    station_icao: str
    station_name: str
    latitude: float
    longitude: float
    timezone: str
    unit: str  # "F" for US cities, "C" for non-US cities
    country: str
    foreca_id: str
    accuweather_prefix: str
    accuweather_key: str
    platforms: str = "polymarket_global"  # "polymarket_global", "polymarket_us", or "both"

    @property
    def geohash(self) -> str:
        return encode_geohash(self.latitude, self.longitude, precision=9)

    @property
    def meteoblue_coord(self) -> str:
        return f"{self.latitude:.3f}N{self.longitude:.3f}E"


